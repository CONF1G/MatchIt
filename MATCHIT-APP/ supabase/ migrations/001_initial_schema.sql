-- Enable required extensions
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- =============================================================================
-- ENUMS
-- =============================================================================

CREATE TYPE lobby_mode AS ENUM ('first_match', 'deck', 'tournament');
CREATE TYPE lobby_status AS ENUM ('waiting', 'in_progress', 'finished', 'cancelled');
CREATE TYPE swipe_action AS ENUM ('like', 'dislike', 'super_like');
CREATE TYPE participant_role AS ENUM ('host', 'player', 'guest');
CREATE TYPE notification_type AS ENUM (
  'lobby_invite', 'lobby_started', 'match_result',
  'new_follower', 'catalog_like', 'comment', 'system'
);

-- =============================================================================
-- PROFILES
-- Extended user data beyond auth.users
-- =============================================================================

CREATE TABLE profiles (
  id            UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  username      TEXT UNIQUE NOT NULL,
  display_name  TEXT,
  avatar_url    TEXT,
  bio           TEXT,
  is_guest      BOOLEAN NOT NULL DEFAULT FALSE,
  guest_code    TEXT UNIQUE,                        -- temporary code for guests
  followers_count INT NOT NULL DEFAULT 0,
  following_count INT NOT NULL DEFAULT 0,
  catalogs_count  INT NOT NULL DEFAULT 0,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =============================================================================
-- FOLLOWS
-- =============================================================================

CREATE TABLE follows (
  id          UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  follower_id UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  following_id UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (follower_id, following_id),
  CHECK (follower_id <> following_id)
);

-- =============================================================================
-- CATALOGS
-- A catalog is a named collection of photos/cards owned by a user
-- =============================================================================

CREATE TABLE catalogs (
  id           UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  owner_id     UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  title        TEXT NOT NULL,
  description  TEXT,
  cover_url    TEXT,
  is_private   BOOLEAN NOT NULL DEFAULT FALSE,
  tags         TEXT[] DEFAULT '{}',
  likes_count  INT NOT NULL DEFAULT 0,
  photos_count INT NOT NULL DEFAULT 0,
  views_count  INT NOT NULL DEFAULT 0,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =============================================================================
-- PHOTOS
-- Individual cards/photos inside a catalog
-- =============================================================================

CREATE TABLE photos (
  id           UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  catalog_id   UUID NOT NULL REFERENCES catalogs(id) ON DELETE CASCADE,
  uploader_id  UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  storage_path TEXT NOT NULL,             -- path in Supabase Storage bucket
  url          TEXT NOT NULL,             -- public URL
  thumbnail_url TEXT,
  title        TEXT,
  description  TEXT,
  ai_tags      TEXT[] DEFAULT '{}',       -- tags generated by AI service
  width        INT,
  height       INT,
  file_size    INT,                       -- bytes
  sort_order   INT NOT NULL DEFAULT 0,
  likes_count  INT NOT NULL DEFAULT 0,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =============================================================================
-- CATALOG LIKES
-- =============================================================================

CREATE TABLE catalog_likes (
  id         UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  catalog_id UUID NOT NULL REFERENCES catalogs(id) ON DELETE CASCADE,
  user_id    UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (catalog_id, user_id)
);

-- =============================================================================
-- PHOTO LIKES
-- =============================================================================

CREATE TABLE photo_likes (
  id         UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  photo_id   UUID NOT NULL REFERENCES photos(id) ON DELETE CASCADE,
  user_id    UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (photo_id, user_id)
);

-- =============================================================================
-- COMMENTS
-- Comments on catalogs
-- =============================================================================

CREATE TABLE comments (
  id         UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  catalog_id UUID NOT NULL REFERENCES catalogs(id) ON DELETE CASCADE,
  author_id  UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  parent_id  UUID REFERENCES comments(id) ON DELETE CASCADE,  -- for replies
  body       TEXT NOT NULL CHECK (char_length(body) BETWEEN 1 AND 1000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =============================================================================
-- LOBBIES
-- A game session / match lobby
-- =============================================================================

CREATE TABLE lobbies (
  id           UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  host_id      UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  catalog_id   UUID REFERENCES catalogs(id) ON DELETE SET NULL,
  title        TEXT,
  mode         lobby_mode NOT NULL DEFAULT 'first_match',
  status       lobby_status NOT NULL DEFAULT 'waiting',
  invite_code  TEXT UNIQUE NOT NULL DEFAULT upper(substring(gen_random_uuid()::text, 1, 6)),
  max_players  INT NOT NULL DEFAULT 8 CHECK (max_players BETWEEN 2 AND 20),
  is_public    BOOLEAN NOT NULL DEFAULT FALSE,
  settings     JSONB NOT NULL DEFAULT '{}',   -- mode-specific config
  started_at   TIMESTAMPTZ,
  finished_at  TIMESTAMPTZ,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =============================================================================
-- LOBBY PARTICIPANTS
-- Players (registered or guest) in a lobby
-- =============================================================================

CREATE TABLE lobby_participants (
  id         UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  lobby_id   UUID NOT NULL REFERENCES lobbies(id) ON DELETE CASCADE,
  user_id    UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  role       participant_role NOT NULL DEFAULT 'player',
  score      INT NOT NULL DEFAULT 0,
  is_ready   BOOLEAN NOT NULL DEFAULT FALSE,
  joined_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  left_at    TIMESTAMPTZ,
  UNIQUE (lobby_id, user_id)
);

-- =============================================================================
-- SWIPE SESSIONS
-- One swipe session per participant per lobby
-- =============================================================================

CREATE TABLE swipe_sessions (
  id              UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  lobby_id        UUID NOT NULL REFERENCES lobbies(id) ON DELETE CASCADE,
  participant_id  UUID NOT NULL REFERENCES lobby_participants(id) ON DELETE CASCADE,
  total_cards     INT NOT NULL DEFAULT 0,
  cards_swiped    INT NOT NULL DEFAULT 0,
  likes_count     INT NOT NULL DEFAULT 0,
  started_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  completed_at    TIMESTAMPTZ,
  UNIQUE (lobby_id, participant_id)
);

-- =============================================================================
-- SWIPES
-- Individual card swipe actions within a session
-- =============================================================================

CREATE TABLE swipes (
  id          UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  session_id  UUID NOT NULL REFERENCES swipe_sessions(id) ON DELETE CASCADE,
  photo_id    UUID NOT NULL REFERENCES photos(id) ON DELETE CASCADE,
  action      swipe_action NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (session_id, photo_id)
);

-- =============================================================================
-- MATCHES
-- When 2+ participants swipe right on the same photo → a match event
-- =============================================================================

CREATE TABLE matches (
  id         UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  lobby_id   UUID NOT NULL REFERENCES lobbies(id) ON DELETE CASCADE,
  photo_id   UUID NOT NULL REFERENCES photos(id) ON DELETE CASCADE,
  matched_by UUID[] NOT NULL DEFAULT '{}',   -- array of profile ids who liked
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =============================================================================
-- NOTIFICATIONS
-- =============================================================================

CREATE TABLE notifications (
  id         UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  user_id    UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  type       notification_type NOT NULL,
  title      TEXT NOT NULL,
  body       TEXT,
  data       JSONB NOT NULL DEFAULT '{}',    -- contextual payload (lobby_id, etc.)
  is_read    BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =============================================================================
-- INDEXES
-- =============================================================================

-- Profiles
CREATE INDEX idx_profiles_username ON profiles(username);
CREATE INDEX idx_profiles_is_guest ON profiles(is_guest);

-- Follows
CREATE INDEX idx_follows_follower   ON follows(follower_id);
CREATE INDEX idx_follows_following  ON follows(following_id);

-- Catalogs
CREATE INDEX idx_catalogs_owner     ON catalogs(owner_id);
CREATE INDEX idx_catalogs_private   ON catalogs(is_private);
CREATE INDEX idx_catalogs_created   ON catalogs(created_at DESC);
CREATE INDEX idx_catalogs_tags      ON catalogs USING GIN(tags);

-- Photos
CREATE INDEX idx_photos_catalog     ON photos(catalog_id);
CREATE INDEX idx_photos_uploader    ON photos(uploader_id);
CREATE INDEX idx_photos_sort        ON photos(catalog_id, sort_order);
CREATE INDEX idx_photos_ai_tags     ON photos USING GIN(ai_tags);

-- Comments
CREATE INDEX idx_comments_catalog   ON comments(catalog_id);
CREATE INDEX idx_comments_author    ON comments(author_id);
CREATE INDEX idx_comments_parent    ON comments(parent_id);

-- Lobbies
CREATE INDEX idx_lobbies_host       ON lobbies(host_id);
CREATE INDEX idx_lobbies_status     ON lobbies(status);
CREATE INDEX idx_lobbies_code       ON lobbies(invite_code);
CREATE INDEX idx_lobbies_public     ON lobbies(is_public) WHERE is_public = TRUE;

-- Lobby participants
CREATE INDEX idx_lp_lobby           ON lobby_participants(lobby_id);
CREATE INDEX idx_lp_user            ON lobby_participants(user_id);

-- Swipes
CREATE INDEX idx_swipes_session     ON swipes(session_id);
CREATE INDEX idx_swipes_photo       ON swipes(photo_id);
CREATE INDEX idx_swipes_action      ON swipes(action);

-- Matches
CREATE INDEX idx_matches_lobby      ON matches(lobby_id);
CREATE INDEX idx_matches_photo      ON matches(photo_id);

-- Notifications
CREATE INDEX idx_notif_user         ON notifications(user_id);
CREATE INDEX idx_notif_read         ON notifications(user_id, is_read) WHERE is_read = FALSE;
CREATE INDEX idx_notif_created      ON notifications(created_at DESC);
